def validate_python(source: str, name: str) -> str:
    ast.parse(source, filename=name)
    # Formatting and linting are performed on text; no generated code is imported.
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", name, "-"],
        input=source,
        capture_output=True,
        text=True,
        shell=False,
        timeout=30,
    )
    if formatted.returncode:
        raise ValueError(f"Generated code formatting failed: {name}; install Ruff with uv sync.")
    checked = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--select",
            "E4,E7,E9,F",
            "--stdin-filename",
            name,
            "-",
        ],
        input=formatted.stdout,
        capture_output=True,
        text=True,
        shell=False,
        timeout=30,
    )
    if checked.returncode:
        raise ValueError(f"Generated code lint failed: {name}: {checked.stdout}")
    return formatted.stdout


