def digest(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def generate(project: Project, *, authorization: AuthorizationContext | None = None) -> list[str]:
    require_authorization(authorization, project.root, "generate")
    cases = [c for c in project.cases() if c.review_status == "approved" and c.feasible]
    if not cases:
        raise ValueError(
            "No approved automatable scenarios. Review test-matrix.md and use plan --approve ID."
        )
    if len({c.id.replace("-", "_") for c in cases}) != len(cases):
        raise ValueError("Scenario IDs collide after Python name normalization.")
    discovery = project.discovery()
    scope = Scope(project.config.application_url, project.config)
    source = '"""Observation-based regression tests. Review expectations before delivery."""\nfrom playwright.sync_api import expect\n\n'
    if any(
        c.contract and any(a["check"] == "ordered" for a in c.contract["assertions"]) for c in cases
    ):
        source = source.replace(
            "from playwright.sync_api", "import re\n\nfrom playwright.sync_api", 1
        )
    for case in cases:
        scope.validate(case.url)
        observed = next((p for p in discovery.pages if p.url == case.url), None)
        if observed is None:
            raise ValueError(f"{case.id} has no matching browser evidence; explore and plan again.")
        source += f"\ndef test_{case.id.replace('-', '_')}(qa_page):\n    page, resolve = qa_page\n    page.goto(resolve({case.url!r}), wait_until='domcontentloaded')\n"
        if case.kind == "functional":
            from autoqa.functional import render_functional

            local = scope.config.allow_localhost and urlsplit(scope.base).hostname in {
                "localhost",
                "127.0.0.1",
                "::1",
            }
            source += render_functional(case, discovery, local=local)
            continue
        if case.kind == "heading":
            if case.target not in observed.headings:
                raise ValueError(f"{case.id} heading lacks evidence.")
            heading = case.target
        elif case.kind == "link":
            scope.validate(case.destination)
            if not any(
                e.kind == "a" and e.name == case.target and e.href == case.destination
                for e in observed.elements
            ):
                raise ValueError(f"{case.id} link lacks evidence.")
            destination = next((p for p in discovery.pages if p.url == case.destination), None)
            if not destination or not destination.headings:
                raise ValueError(f"{case.id} destination lacks evidence.")
            heading = destination.headings[0]
            source += f"    page.get_by_role('link', name={case.target!r}, exact=True).first.click()\n    expect(page).to_have_url(resolve({case.destination!r}))\n"
        else:
            raise ValueError(f"{case.id} requires manual implementation.")
        source += f"    expect(page.get_by_role('heading', name={heading!r}, exact=True).first).to_be_visible()\n"
    files = {"test_observed.py": source, "conftest.py": FIXTURE}
    files = {name: validate_python(content, name) for name, content in files.items()}
    root = project.root / "automation"
    # Refuse to silently replace hand-maintained suite files.
    prior = load_json(root / "manifest.json") if (root / "manifest.json").exists() else None
    for path in root.glob("*.py"):
        if (
            not prior
            or path.name not in prior["files"]
            or digest(path.read_text(encoding="utf-8")) != prior["files"][path.name]
        ):
            raise ValueError(
                f"Preserve modified/unmanaged file {path.name}; move it out before regenerating."
            )
    for case in cases:
        verify_approval_binding(project, case)
    for name, content in files.items():
        (root / name).write_text(content, encoding="utf-8")
    save_json(
        root / "manifest.json",
        {
            "version": "0.2.0",
            "approval_binding": "required",
            "files": {name: digest(content) for name, content in files.items()},
            "cases": {c.id: case_signature(c) for c in cases},
        },
    )
    project.audit(f"Generated {len(cases)} approved tests")
    return [c.id for c in cases]


def parse_junit(path: Path) -> list[dict]:
    if not path.exists():
        return []
    records = []
    for node in ET.parse(path).getroot().iter("testcase"):
        status, error = "PASSED", ""
        for tag, value in (("error", "ERROR"), ("failure", "FAILED"), ("skipped", "SKIPPED")):
            failure = node.find(tag)
            if failure is not None:
                status, error = value, (failure.text or failure.get("message", ""))[:12000]
                break
        name = node.get("name", "unknown")
        records.append(
            {
                "id": name.removeprefix("test_").replace("_", "-"),
                "name": name,
                "status": status,
                "duration": float(node.get("time", "0")),
                "error": error,
            }
        )
    return records


def run(project: Project, *, authorization: AuthorizationContext | None = None) -> dict:
    require_authorization(authorization, project.root, "execute")
    root = project.root / "automation"
    manifest = load_json(root / "manifest.json")
    if set(manifest["files"]) != {"conftest.py", "test_observed.py"}:
        raise ValueError("Unexpected automation manifest.")
    for path in root.rglob("*.py"):
        if path.parent != root or path.name not in manifest["files"]:
            raise ValueError("Unmanaged Python files in automation directory.")
    for name, expected in manifest["files"].items():
        if digest((root / name).read_text(encoding="utf-8")) != expected:
            raise ValueError(
                "Automation changed after generation. Review and regenerate before running."
            )
        validate_python((root / name).read_text(encoding="utf-8"), name)
    current = {c.id: c for c in project.cases()}
    for test_id, signature in manifest["cases"].items():
        if (
            test_id not in current
            or current[test_id].review_status != "approved"
            or case_signature(current[test_id]) != signature
        ):
            raise ValueError("Approvals changed; regenerate the suite.")
    if manifest.get("approval_binding") == "required":
        for test_id in manifest["cases"]:
            verify_approval_binding(project, current[test_id])
    base = os.environ.get("AUTOQA_BASE_URL", project.config.application_url)
    Scope(base, project.config)
    run_id = datetime.now(UTC).strftime("%Y%m%dT%H%M%S") + "-" + uuid.uuid4().hex[:8]
    output = project.root / "artifacts" / run_id
    output.mkdir()
    # Only trusted templates are accepted. This is process isolation, not an OS sandbox.
    keep = {
        "SYSTEMROOT",
        "WINDIR",
        "PATH",
        "TEMP",
        "TMP",
        "USERPROFILE",
        "LOCALAPPDATA",
        "APPDATA",
        "COMSPEC",
        "PLAYWRIGHT_BROWSERS_PATH",
    }
    env = {key: value for key, value in os.environ.items() if key.upper() in keep}
    env.update(PYTEST_DISABLE_PLUGIN_AUTOLOAD="1", AUTOQA_RUN_DIR=str(output), AUTOQA_BASE_URL=base)
    command = [
        sys.executable,
        "-m",
        "pytest",
        "-c",
        "pytest.ini",
        "--rootdir",
        str(root),
        "--confcutdir",
        str(root),
        "--junitxml",
        str(output / "junit.xml"),
        "-q",
        "test_observed.py",
    ]
    (root / "pytest.ini").write_text("[pytest]\naddopts =\n", encoding="utf-8")
    started = time.monotonic()
    try:
        collection = subprocess.run(
            command + ["--collect-only"],
            cwd=root,
            env=env,
            capture_output=True,
            text=True,
            timeout=30,
            shell=False,
        )
        (output / "collection.log").write_text(
            collection.stdout + collection.stderr, encoding="utf-8"
        )
        process = (
            subprocess.run(
                command,
                cwd=root,
                env=env,
                capture_output=True,
                text=True,
                timeout=project.config.overall_timeout_seconds,
                shell=False,
            )
            if collection.returncode == 0
            else collection
        )
        code, stdout = process.returncode, process.stdout + process.stderr
    except subprocess.TimeoutExpired:
        code, stdout = 124, "Execution timeout; results may be incomplete."
    (output / "pytest.log").write_text(stdout, encoding="utf-8")
    records = parse_junit(output / "junit.xml")
    name_to_id = {"test_" + test_id.replace("-", "_"): test_id for test_id in manifest["cases"]}
    for record in records:
        record["id"] = name_to_id.get(record["name"], record["id"])
    recorded = {r["id"] for r in records}
    for test_id in manifest["cases"]:
        if test_id not in recorded:
            records.append(
                {
                    "id": test_id,
                    "name": test_id,
                    "status": "NOT_EXECUTED",
                    "duration": 0,
                    "error": "No JUnit testcase was emitted; inspect pytest.log.",
                }
            )
    result = {
        "run_id": run_id,
        "created_at": datetime.now(UTC).isoformat(),
        "exit_code": code,
        "duration": round(time.monotonic() - started, 3),
        "records": records,
        "artifact_dir": f"artifacts/{run_id}",
        "base_url": base,
        "case_snapshot": [current[test_id].model_dump() for test_id in manifest["cases"]],
        "planning_snapshot": [c.model_dump() for c in current.values()],
        "discovery_snapshot": project.discovery().model_dump(),
    }
    save_json(output / "results.json", result)
    save_json(project.root / "reports/latest-run.json", result)
    project.audit(f"Run {run_id}: exit {code}")
    return result
